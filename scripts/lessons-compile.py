#!/usr/bin/env python3
"""Compiles the lessons source into the three lesson views.

    python3 tools/lessons-compile.py            # writes the views
    python3 tools/lessons-compile.py --check    # exit 1 as soon as a view differs
    python3 tools/lessons-compile.py --self-test  # round trip on a temporary fixture, exit 1 on failure

Source: `.claude/lessons.jsonl`, one JSON record per line, three targets:

    learnings       -> .claude/skills/<skill>/references/learnings.md
    known-mistakes  -> .claude/rules/known-mistakes.md (section feit|werkwijze)
    denylist        -> .claude/known-bad.json (field `entry` goes in verbatim)

Why this exists: the three views were maintained by hand in parallel, and that
is exactly the drift class check F once caught with the gate steps. Machine
readable state belongs in JSON besides: a model rewrites markdown unintentionally
sooner than JSON (memory research 2026-09-01, first-hand measurement by
Anthropic's harness team). The lesson text itself stays prose in the owner's
language in the field `md`; promotion along the chain is a field change (`doel`,
`skill` or `sectie`), not a copy. `owner-taste.md` remains the owner's literal
voice and is deliberately never compiled.

Record fields: `id`, `doel`, `datum`, `md` (the literal line, including the
leading `- `), `status` (`actief`), and per target: `skill` plus `soort` and
where parseable `regel`/`bewijs`/`grens` (learnings), `sectie` plus `regel`/
`bron`/`afgedwongen` (known-mistakes), `entry` (denylist). `lege_regel_ervoor`
preserves a deliberate blank line between groups.

A learnings view above 30 lines is an error (lessons protocol): merge the
oldest still valid lessons into the SKILL.md and set the record to
`status: gearchiveerd` instead of stretching the cap.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(os.environ["CLAUDE_PROJECT_DIR"]).resolve() if os.environ.get("CLAUDE_PROJECT_DIR") else Path.cwd()
SOURCE = REPO / ".claude" / "lessons.jsonl"
KNOWN_MISTAKES = REPO / ".claude" / "rules" / "known-mistakes.md"
KNOWN_BAD = REPO / ".claude" / "known-bad.json"
SKILLS_DIR = REPO / ".claude" / "skills"

LEARNINGS_MAX_LINES = 30

GEGENEREERD = "<!-- generated by tools/lessons-compile.py; edit .claude/lessons.jsonl, never this file -->"

LEARNINGS_KOP = "# Learnings: proven lessons only; format and threshold are in SKILL.md under ## Learnings."

KM_FRONTMATTER = """---
paths:
  - "src/**"
  - "tests/**"
  - "tools/**"
  - "default.project.json"
  - ".claude/**"
---
"""

KM_INTRO = """
# Known mistakes: made once, recorded here, not again

One line per lesson, three kinds. **Fact**: an API, a number or a pitfall of
the platform. **Practice**: how we work. **Taste**: owner verdicts on delivered
work; those live verbatim in `.claude/skills/_shared/owner-taste.md` and not
here. A fact that rejects an API or setting also gets a rule in
`.claude/known-bad.json`: then `tools/check-denylist.py` (PreToolUse) refuses
every Edit or Write that reintroduces it, and `tools/claude-config-guard.py`
(check E) reports every place where it still stands. Per skill,
`references/learnings.md` remains the workshop; what is stable there and applies
to more than one skill moves here (protocol: `.claude/skills/_shared/learnings-protocol.md`).

Format: `- [YYYY-MM-DD] mistake -> what instead; source: <path or measurement>; enforced: <hook, guard or no>`
"""

KM_SMAAK = """## Taste

Owner verdicts live verbatim in `.claude/skills/_shared/owner-taste.md`; no copy here.
"""

KB_COMMENT_SUFFIX = (
    " Compiled by tools/lessons-compile.py from .claude/lessons.jsonl; "
    "edit the source, never this file."
)

# The compiler suffix is stripped from the existing `$comment` before the
# current one is appended; the second marker is the pre-translation suffix
# still present in older compiled files.
KB_COMMENT_MARKERS = (" Compiled by ", " Gecompileerd door ")


def load_records() -> list[dict]:
    if not SOURCE.exists():
        raise SystemExit(f"ERROR: {SOURCE.relative_to(REPO)} is missing; there is nothing to compile.")
    records: list[dict] = []
    for lineno, line in enumerate(SOURCE.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError as exc:
            raise SystemExit(f"ERROR: {SOURCE.relative_to(REPO)} line {lineno}: {exc}") from exc
        for veld in ("id", "doel", "status"):
            if veld not in record:
                raise SystemExit(f"ERROR: record on line {lineno} is missing field `{veld}`")
        records.append(record)
    ids = [record["id"] for record in records]
    dubbel = {naam for naam in ids if ids.count(naam) > 1}
    if dubbel:
        raise SystemExit(f"ERROR: duplicate record ids: {', '.join(sorted(dubbel))}")
    return records


def actief(records: list[dict], doel: str) -> list[dict]:
    return [record for record in records if record["doel"] == doel and record["status"] == "actief"]


def render_learnings(records: list[dict]) -> str:
    regels = [LEARNINGS_KOP, GEGENEREERD, ""]
    for record in records:
        if record.get("lege_regel_ervoor"):
            regels.append("")
        regels.append(record["md"])
    if len(regels) > LEARNINGS_MAX_LINES:
        raise SystemExit(
            f"ERROR: learnings view for {records[0]['skill']} has {len(regels)} lines "
            f"(limit {LEARNINGS_MAX_LINES}); merge the oldest lessons into the SKILL.md "
            "and archive their records (lessons protocol)."
        )
    return "\n".join(regels) + "\n"


def render_known_mistakes(records: list[dict]) -> str:
    feiten = [record["md"] for record in records if record["sectie"] == "feit"]
    werkwijzen = [record["md"] for record in records if record["sectie"] == "werkwijze"]
    return (
        KM_FRONTMATTER
        + GEGENEREERD + "\n"
        + KM_INTRO
        + "\n## Fact\n\n"
        + "\n".join(feiten)
        + "\n\n## Practice\n\n"
        + "\n".join(werkwijzen)
        + "\n\n"
        + KM_SMAAK
    )


def render_known_bad(records: list[dict], huidig_comment: str) -> str:
    basis = huidig_comment
    for marker in KB_COMMENT_MARKERS:
        basis = basis.split(marker)[0]
    data = {
        "$comment": basis + KB_COMMENT_SUFFIX,
        "entries": [record["entry"] for record in records],
    }
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def views(records: list[dict]) -> dict[Path, str]:
    uitkomst: dict[Path, str] = {}

    per_skill: dict[str, list[dict]] = {}
    for record in actief(records, "learnings"):
        per_skill.setdefault(record["skill"], []).append(record)
    for skill, skill_records in per_skill.items():
        pad = SKILLS_DIR / skill / "references" / "learnings.md"
        uitkomst[pad] = render_learnings(skill_records)

    uitkomst[KNOWN_MISTAKES] = render_known_mistakes(actief(records, "known-mistakes"))

    huidig_comment = ""
    if KNOWN_BAD.exists():
        huidig_comment = json.loads(KNOWN_BAD.read_text(encoding="utf-8")).get("$comment", "")
    uitkomst[KNOWN_BAD] = render_known_bad(actief(records, "denylist"), huidig_comment)
    return uitkomst


SELF_TEST_RECORDS = [
    {"id": "l1", "doel": "learnings", "datum": "2026-09-01", "status": "actief", "skill": "fixture-skill",
     "soort": "feit", "md": "- [2026-09-01] fixture learning line"},
    {"id": "k1", "doel": "known-mistakes", "datum": "2026-09-01", "status": "actief", "sectie": "feit",
     "md": "- [2026-09-01] fixture fact -> use the other thing; source: fixture; enforced: no"},
    {"id": "k2", "doel": "known-mistakes", "datum": "2026-09-01", "status": "actief", "sectie": "werkwijze",
     "md": "- [2026-09-01] fixture practice -> do it this way; source: fixture; enforced: no"},
    {"id": "d1", "doel": "denylist", "datum": "2026-09-01", "status": "actief",
     "entry": {"id": "fixture-rule", "category": "feit", "pattern": "Fixture\\.Wrong", "reason": "fixture",
               "use": "Fixture.Right", "date": "2026-09-01", "source": "fixture", "paths": ["src/**"]}},
    {"id": "old", "doel": "learnings", "datum": "2026-08-01", "status": "gearchiveerd", "skill": "fixture-skill",
     "soort": "feit", "md": "- [2026-08-01] archived, must not appear"},
]


def _run_in(repo: Path, *flags: str) -> subprocess.CompletedProcess:
    env = dict(os.environ, CLAUDE_PROJECT_DIR=str(repo))
    return subprocess.run([sys.executable, __file__, *flags], env=env, capture_output=True, text=True, check=False)


def self_test() -> int:
    """Compile a fixture in a temporary repo, then prove --check is green, red after drift, green again."""
    with tempfile.TemporaryDirectory(prefix="lessons-self-test-") as tmp:
        repo = Path(tmp).resolve()
        source = repo / ".claude" / "lessons.jsonl"
        # The compiler writes into existing skill and rules directories, as in a real project.
        (repo / ".claude" / "skills" / "fixture-skill" / "references").mkdir(parents=True)
        (repo / ".claude" / "rules").mkdir(parents=True)
        source.write_text("".join(json.dumps(record) + "\n" for record in SELF_TEST_RECORDS), encoding="utf-8")

        steps = [
            ("compile", (), 0),
            ("check after compile", ("--check",), 0),
        ]
        for label, flags, expected in steps:
            run = _run_in(repo, *flags)
            if run.returncode != expected:
                print(f"FAIL {label}: exit {run.returncode}, expected {expected}\n{run.stderr.strip()}")
                return 1

        learnings = repo / ".claude" / "skills" / "fixture-skill" / "references" / "learnings.md"
        known_bad = repo / ".claude" / "known-bad.json"
        if "archived, must not appear" in learnings.read_text(encoding="utf-8"):
            print("FAIL archived record leaked into the learnings view")
            return 1
        if json.loads(known_bad.read_text(encoding="utf-8"))["entries"][0]["id"] != "fixture-rule":
            print("FAIL denylist view does not carry the fixture entry")
            return 1

        learnings.write_text(learnings.read_text(encoding="utf-8") + "- drifted by hand\n", encoding="utf-8")
        run = _run_in(repo, "--check")
        if run.returncode != 1 or "LESSONS SOURCE DIFFERS" not in run.stderr:
            print(f"FAIL check after drift: exit {run.returncode}, expected 1 with a drift message")
            return 1
        run = _run_in(repo)
        if run.returncode != 0 or _run_in(repo, "--check").returncode != 0:
            print("FAIL recompile after drift did not restore a green check")
            return 1
    print("LESSONS SELF-TEST PASS")
    return 0


def main() -> int:
    if "--self-test" in sys.argv:
        return self_test()
    check = "--check" in sys.argv
    afwijkend: list[str] = []
    for pad, inhoud in views(load_records()).items():
        huidig = pad.read_text(encoding="utf-8") if pad.exists() else ""
        if huidig == inhoud:
            continue
        if check:
            afwijkend.append(str(pad.relative_to(REPO)))
        else:
            pad.write_text(inhoud, encoding="utf-8")
            print(f"written: {pad.relative_to(REPO)}")
    if check:
        if afwijkend:
            print(
                "LESSONS SOURCE DIFFERS from the views: " + ", ".join(afwijkend)
                + "; run python3 tools/lessons-compile.py",
                file=sys.stderr,
            )
            return 1
        print("lessons source and views in sync")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
